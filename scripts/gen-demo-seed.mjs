// Generates supabase/seed-demo.sql from the phase 1 example data.
// Demo accounts can't sign in (no password); they only give a staging
// database something to show. Never run the output on production.
//   node scripts/gen-demo-seed.mjs
import { writeFileSync } from "node:fs";
import { LISTINGS, USERS } from "./demo-data.ts";

const q = (s) => (s === null || s === undefined ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(", ")}]::text[]`;
const uid = (username) => `md5('truxanger-demo:${username}')::uuid`;

const out = [
  "-- Demo content for staging. NEVER run on production.",
  "-- Generated by scripts/gen-demo-seed.mjs. Accounts have no password and cannot sign in.",
  "begin;",
];

for (const u of USERS.filter((x) => x.id !== "cesar_trux")) {
  out.push(
    `insert into auth.users (id, instance_id, aud, role, email, email_confirmed_at, raw_user_meta_data, created_at, updated_at)
values (${uid(u.username)}, '00000000-0000-0000-0000-000000000000', 'authenticated', 'authenticated', ${q(`${u.username}@demo.truxange.com`)}, now(), jsonb_build_object('full_name', ${q(u.displayName)}), now(), now())
on conflict (id) do nothing;`,
    `update public.profiles set username = ${q(u.username.replace(/[^a-z0-9_.]/g, "_"))}, display_name = ${q(u.displayName)}, bio = ${q(u.bio)},
  city_slug = ${q(u.citySlug)}, neighborhood = ${q(u.neighborhood)} where id = ${uid(u.username)};`,
  );
}

for (const l of LISTINGS.filter((x) => !x.id.startsWith("m"))) {
  out.push(
    `insert into public.listings (owner_id, slug, title, description, category, condition, value, currency, photos, wants, open_to_anything, accepts_cash, has_video, city_slug, neighborhood, lat, lng, created_at)
values (${uid(l.ownerId)}, ${q(l.slug.replace(/-l\d+$/, "-demo"))}, ${q(l.title)}, ${q(l.description)}, ${q(l.category)}, ${q(l.condition)}, ${l.value ?? "null"}, ${q(l.currency)},
  ${arr([`demo:${l.category}`])}, ${arr(l.wants)}, ${l.openToAnything}, ${l.acceptsCash}, ${l.hasVideo}, ${q(l.citySlug)}, ${q(l.neighborhood)},
  ${l.location?.lat ?? "null"}, ${l.location?.lng ?? "null"}, ${q(`${l.createdAt}T12:00:00Z`)})
on conflict (slug) do nothing;`,
  );
}

out.push("commit;", "");
writeFileSync("supabase/seed-demo.sql", out.join("\n"));
console.log(`wrote supabase/seed-demo.sql (${USERS.length - 1} accounts, ${LISTINGS.length - 3} listings)`);
