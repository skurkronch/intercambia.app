// Points demo listings at the photos dropped in public/demo/<slug>/.
// Writes supabase/demo-photos.sql to paste into the Supabase SQL Editor.
//   npm run db:demo-photos
import { existsSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const ROOT = "public/demo";
const IMAGE = /\.(jpe?g|png|webp|avif)$/i;
const MAX_PHOTOS = 6;
const MAX_BYTES = 1024 * 1024;

const q = (s) => `'${s.replace(/'/g, "''")}'`;
const lines = ["-- Demo listing photos from public/demo/. Generated by scripts/demo-photos.mjs.", "begin;"];
const warnings = [];
let withPhotos = 0;

for (const slug of readdirSync(ROOT).filter((d) => statSync(join(ROOT, d)).isDirectory()).sort()) {
  const files = readdirSync(join(ROOT, slug))
    .filter((f) => IMAGE.test(f))
    .sort((a, b) => a.localeCompare(b, "es", { numeric: true }));
  for (const f of files) {
    const size = statSync(join(ROOT, slug, f)).size;
    if (size > MAX_BYTES) warnings.push(`${slug}/${f} pesa ${(size / 1024 / 1024).toFixed(1)} MB; conviene bajarla a menos de 1 MB.`);
  }
  if (files.length > MAX_PHOTOS) warnings.push(`${slug}: tiene ${files.length} fotos; solo se usan las primeras ${MAX_PHOTOS}.`);
  const used = files.slice(0, MAX_PHOTOS);
  if (!used.length) continue;
  withPhotos++;
  const paths = used.map((f) => q(`demo-file:${slug}/${f}`)).join(", ");
  lines.push(`update public.listings set photos = array[${paths}] where slug = ${q(slug)};`);
}

lines.push("commit;", "");
if (!existsSync("supabase")) throw new Error("Corre el script desde la raíz del proyecto.");
writeFileSync("supabase/demo-photos.sql", lines.join("\n"));
console.log(`${withPhotos} objetos con fotos → supabase/demo-photos.sql`);
for (const w of warnings) console.log(`  aviso: ${w}`);
if (!withPhotos) console.log("  No hay fotos todavía. Deja .jpg, .png o .webp en public/demo/<objeto>/");
